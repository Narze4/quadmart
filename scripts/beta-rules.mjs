import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const marker = 'function betaPolicyRequired() { return false; }';
export function betaRules(source) {
  if (source.split(marker).length !== 2) throw Error('Expected exactly one beta policy switch');
  return '// Generated by scripts/beta-rules.mjs; edit firestore.rules instead.\n' + source.replace(marker, 'function betaPolicyRequired() { return true; }');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--deployment') && process.env.GCLOUD_PROJECT !== 'quadmart-beta') throw Error('Beta rules can only be deployed to quadmart-beta');
  const source = await fs.readFile(new URL('../firestore.rules', import.meta.url), 'utf8');
  const target = new URL('../firestore.beta.rules', import.meta.url), generated = betaRules(source);
  if (process.argv.includes('--check')) {
    if (await fs.readFile(target, 'utf8') !== generated) throw Error('Generated beta rules are stale');
    console.log('Beta rules match their source and require admission policy.');
  } else await fs.writeFile(target, generated);
}
